#!/usr/bin/env node
// Generates deploy/silo/redirects.conf (nginx `location =` blocks) from sites/silo/redirects.json.
//   node scripts/gen-nginx-redirects.mjs          write the file
//   node scripts/gen-nginx-redirects.mjs --check  exit 1 if the committed file is stale (CI)
// The output is reviewed and vendored by infra into hllmr-infra deploy/apps/silo-www/.
import { readFileSync, writeFileSync } from "node:fs";
import { fileURLToPath } from "node:url";

const root = fileURLToPath(new URL("../", import.meta.url));
const src = `${root}sites/silo/redirects.json`;
const out = `${root}deploy/silo/redirects.conf`;
const data = JSON.parse(readFileSync(src, "utf8"));

const KEY = /^[a-z0-9][a-z0-9-]{0,63}$/;
const PATH = /^\/[A-Za-z0-9._\/-]*$/;
/** Targets are quoted, so only characters that are safe inside an nginx double-quoted string. */
const TARGET = /^(https:\/\/[A-Za-z0-9.-]+(\/[A-Za-z0-9._~\/?=&%#-]*)?|\/[A-Za-z0-9._~\/?=&%#-]*)$/;

function block(from, status, to) {
  if (!PATH.test(from)) throw new Error(`unsafe redirect source: ${from}`);
  if (!TARGET.test(to)) throw new Error(`unsafe redirect target for ${from}: ${to}`);
  return `location = ${from} { return ${status} "${to}"; }`;
}

const lines = [
  "# GENERATED by scripts/gen-nginx-redirects.mjs from sites/silo/redirects.json. Do not edit.",
  "# Include inside the silo server block. absolute_redirect off keeps local targets relative.",
  "",
  "# /go/<key>: stable link keys for the app, the Discord bot and docs (302: targets may change).",
  ...Object.entries(data.go).map(([k, to]) => {
    if (!KEY.test(k)) throw new Error(`invalid /go/ key: ${k}`);
    return block(`/go/${k}`, 302, to);
  }),
  "",
  "# Vanity paths (302).",
  ...Object.entries(data.vanity).map(([from, to]) => block(from, 302, to)),
  "",
  "# Retired paths (301).",
  ...Object.entries(data.permanent).map(([from, to]) => block(from, 301, to)),
  "",
];
const text = lines.join("\n");

if (process.argv.includes("--check")) {
  let current = "";
  try {
    current = readFileSync(out, "utf8");
  } catch {
    /* missing counts as stale */
  }
  if (current !== text) {
    console.error("deploy/silo/redirects.conf is stale: run `npm run gen:redirects` and commit it");
    process.exit(1);
  }
  console.log("deploy/silo/redirects.conf is up to date");
} else {
  writeFileSync(out, text);
  console.log(`wrote ${out}`);
}
